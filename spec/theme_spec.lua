local wow = require("spec.wow")

describe("Theme", function()
	local ns, w
	before_each(function() ns, w = wow.boot(nil) end)
	after_each(wow.restore)

	it("shares one Arial Narrow font object per size and colour", function()
		local font = ns.Font(13, ns.COLORS.text)
		assert.equal("Font", font.kind)
		assert.equal(font, ns.Font(13, ns.COLORS.text))
		assert.not_equal(font, ns.Font(12, ns.COLORS.text))
		assert.not_equal(font, ns.Font(13, ns.COLORS.muted))
		local text = ns.Text(UIParent, 12, ns.COLORS.muted)
		assert.equal(ns.Font(12, ns.COLORS.muted), text.font)
	end)

	it("draws panels and rules with colour textures only", function()
		local panel = ns.Panel(UIParent, ns.COLORS.panel, ns.COLORS.line)
		assert.equal("BackdropTemplate", panel.template)
		assert.same(ns.COLORS.panel, panel.backdropColor)
		assert.same(ns.COLORS.bg, ns.Panel(UIParent, ns.COLORS.bg).backdropColor)
		assert.same(ns.COLORS.line, ns.Rule(UIParent).color)
	end)

	it("makes flat buttons that lift on hover, amber when primary", function()
		local clicked = 0
		local button = ns.Button(UIParent, "Go", 100, function() clicked = clicked + 1 end)
		assert.equal("Go", button:GetText())
		assert.same(ns.COLORS.raised, button.backdropColor)
		button:Fire("OnEnter")
		assert.same(ns.COLORS.hover, button.backdropColor)
		button:Fire("OnLeave")
		assert.same(ns.COLORS.raised, button.backdropColor)
		button:Fire("OnClick")
		assert.equal(1, clicked)
		local primary = ns.Button(UIParent, "Go", 100, function() end, true)
		assert.same(ns.COLORS.accent, primary.backdropColor)
		primary:Fire("OnEnter")
		assert.same(ns.COLORS.accentHover, primary.backdropColor)
	end)

	it("makes dropdowns that show the current choice and open a menu of radios", function()
		local options = { { "a", "Alpha" }, { "b", "Beta" } }
		local current = "a"
		local dropdown = ns.Dropdown(UIParent, 200, function() return ns.LabelOf(options, current) end, function(root)
			ns.Radios(root, options, function() return current end, function(value) current = value end)
		end)
		assert.equal("Alpha", dropdown.Label:GetText())
		dropdown:Fire("OnClick")
		local root = w.menu.root
		assert.equal(dropdown, w.menu.owner)
		assert.same({ "Alpha", "Beta" }, { root.entries[1].text, root.entries[2].text })
		assert.is_true(root.entries[1].selected())
		assert.is_false(root.entries[2].selected())
		root.entries[2].callback()
		assert.equal("b", current)
		dropdown:Refresh()
		assert.equal("Beta", dropdown.Label:GetText())
		assert.equal("zzz", ns.LabelOf(options, "zzz"))
	end)

	it("makes checkboxes that show their state and toggle it", function()
		local on = true
		local box = ns.Checkbox(UIParent, function() return on end, function(value) on = value end)
		assert.is_true(box.Check:IsShown())
		assert.same(ns.COLORS.accent, box.backdropColor)
		box:Fire("OnClick")
		assert.is_false(on)
		assert.is_false(box.Check:IsShown())
		assert.same(ns.COLORS.raised, box.backdropColor)
	end)
end)
